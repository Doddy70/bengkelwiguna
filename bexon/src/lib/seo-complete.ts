export interface SEOPageConfig {
  seo: RankMathSEO
  pageType: 'homepage' | 'post' | 'page' | 'service' | 'archive'
  slug: string
  baseUrl: string
  breadcrumbs?: Array<{ name: string; url: string }>
}

/**
 * Generate complete SEO metadata for a page
 * Combines Rank Math + custom schemas
 */
export function generateCompleteSEO(config: SEOPageConfig) {
  const { seo, pageType, slug, baseUrl, breadcrumbs } = config

  // Base metadata from Rank Math
  const metadata = generateRankMathMetadata(seo, `${baseUrl}/${slug}`)

  // Additional structured data
  const schemas: Record<string, unknown>[] = []

  // Add schemas based on page type
  switch (pageType) {
    case 'homepage':
      schemas.push(generateWebSiteSchema())
      schemas.push(generateLocalBusinessSchema())
      schemas.push(generateOrganizationSchema())
      break

    case 'post':
      schemas.push(generateArticleSchema({
        title: seo.title,
        slug,
        excerpt: seo.description,
        date: seo.publishedTime || '2024-01-01T00:00:00Z',
      }))
      break

    case 'service':
      schemas.push(generateServiceSchema({
        id: 0,
        title: seo.title,
        slug,
        excerpt: seo.description,
      }))
      break

    case 'archive':
      // Archives don't need specific schemas
      break

    default:
      // Pages get basic organization schema
      schemas.push(generateOrganizationSchema())
  }

  // Add breadcrumb schema if provided
  if (breadcrumbs && breadcrumbs.length > 0) {
    schemas.push(generateBreadcrumbSchema(breadcrumbs))
  }

  // Add FAQ schema if present in Rank Math data
  if (seo.schema?.['@type'] === 'FAQPage') {
    schemas.push(seo.schema)
  }

  // Add AI Custom Schema if generated by BW Headless CMS Agent
  if (seo.schema?.bw_ai_custom_schema) {
    schemas.push(seo.schema.bw_ai_custom_schema as Record<string, unknown>)
  }

  return {
    metadata,
    schemas,
    specluationRules: generateSpeculationRules({
      eagerness: 'moderate',
      excludePatterns: ['/booking/*', '/checkout/*', '/admin/*'],
    }),
  }
}

/**
 * Generate breadcrumbs from URL path
 */
export function generateBreadcrumbsFromPath(path: string, baseUrl: string): Array<{ name: string; url: string }> {
  const segments = path.split('/').filter(Boolean)
  const breadcrumbs: Array<{ name: string; url: string }> = [
    { name: 'Home', url: baseUrl },
  ]

  let currentPath = ''
  const nameMap: Record<string, string> = {
    services: 'Layanan',
    blog: 'Blog',
    lokasi: 'Lokasi',
    contact: 'Kontak',
    tentang: 'Tentang Kami',
  }

  segments.forEach((segment, index) => {
    currentPath += `/${segment}`
    const name = nameMap[segment] || segment.replace(/-/g, ' ').replace(/\b\w/g, (l) => l.toUpperCase())
    breadcrumbs.push({
      name,
      url: `${baseUrl}${currentPath}`,
    })
  })

  return breadcrumbs
}


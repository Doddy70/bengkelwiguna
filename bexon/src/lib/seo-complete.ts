/**
 * Generate Next.js 13+ metadata object
 */
export function generatePageMetadata(config: SEOPageConfig) {
  const { seo, slug, baseUrl, breadcrumbs } = config

  // Generate complete SEO data
  const seoData = generateCompleteSEO(config)

  // Build metadata for Next.js
  return {
    ...seoData.metadata,

    // Additional metadata
    metadataBase: new URL(baseUrl),

    // Format URLs
    alternates: {
      canonical: seo.canonical || `${baseUrl}/${slug}`,
      languages: {
        'id-ID': `${baseUrl}/${slug}`,
      },
    },

    // Note: Google verification is handled in root layout.js via GSC_VERIFICATION const
    // Do NOT duplicate it here to avoid double meta tags

    // Additional metadata if any
    ...(seo.publishedTime && {
      other: {
        'article:published_time': seo.publishedTime,
        'article:modified_time': seo.modifiedTime || seo.publishedTime,
      }
    }),
  }
}

/**
 * Generate JSON-LD script tags for Next.js
 */
export function generateJSONLDScripts(schemas: Record<string, unknown>[]) {
  return schemas.map((schema, index) => ({
    type: 'application/ld+json' as const,
    props: {
      key: `json-ld-${index}`,
      dangerouslySetInnerHTML: {
        __html: JSON.stringify(schema),
      },
    },
  }))
}

/**
 * Generate Speculation Rules script
 */
export function generateSpeculationScript(speculationRules: Record<string, unknown>) {
  return {
    type: 'application/json' as const,
    props: {
      key: 'speculation-rules',
      dangerouslySetInnerHTML: {
        __html: JSON.stringify(speculationRules),
      },
    },
  }
}


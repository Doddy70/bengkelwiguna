export const homepageSEOTemplate = `
// app/(pages)/layout.tsx
import { generateCompleteSEO } from '@/lib/seo-complete'
import { getHomePageData } from '@/lib/wordpress'

export default async function HomeLayout({ children }) {
  // Fetch homepage data
  const data = await getHomePageData()

  // Generate complete SEO
  const seo = extractRankMathSEO(data.pageData)
  const seoData = generateCompleteSEO({
    seo,
    pageType: 'homepage',
    slug: '',
    baseUrl: 'https://bengkelwiguna.com',
  })

  return (
    <>
      {/* JSON-LD Structured Data */}
      {generateJSONLDScripts(seoData.schemas).map((script) => (
        <script key={script.props.key} {...script} />
      ))}

      {/* Speculation Rules for instant navigation */}
      <script
        type="application/speculationrules"
        {...generateSpeculationScript(seoData.speculationRules).props}
      />

      {children}
    </>
  )
}
`

